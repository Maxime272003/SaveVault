const dicts: Record<Lang, Record<Key, string>> = { fr, en };

export const i18n = $state<{ lang: Lang }>({ lang: "fr" });

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const raw = dicts[i18n.lang][key] ?? fr[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** Message lisible pour une erreur renvoyée par le backend. */
export function errorText(e: unknown): string {
  const msg = String(e instanceof Error ? e.message : e);
  const key = `err.${msg}` as Key;
  return key in fr ? t(key) : msg;
}
